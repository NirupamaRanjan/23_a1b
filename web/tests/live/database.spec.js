import { test, expect } from '@playwright/test';

// No API interception: run against the locally seeded stack in explicit demo mode.
// The test books a real visit, discharges it and retains its audit record.
test('real seeded database: six screens, booking trigger, clinic status flow and refresh', async ({ page }) => {
    await page.context().grantPermissions(['geolocation']);
    await page.context().setGeolocation({ latitude: 17.445376, longitude: 78.346144 });
    const errors = [];
    page.on('pageerror', (error) => errors.push(error.message));
    const pause = () => page.waitForTimeout(1800);
    await page.goto('/browse');
    await expect(page.getByRole('heading', { level: 1 })).toBeVisible();
    const session = await (await page.request.get('/api/v1/session')).json();
    expect(session.demo_mode).toBe(true);
    expect(session.actor.role).toBe('patient');
    const clinic = session.clinic;
    await page.getByRole('button', { name: `View details: ${clinic.name}`, exact: true }).click();
    await expect(page.getByRole('button', { name: 'Book at this clinic' })).toBeVisible();
    await pause();
    await page.getByRole('button', { name: 'Book at this clinic' }).click();
    await page.getByLabel('Copay amount').fill('25.00');
    const response = page.waitForResponse((response) => response.url().endsWith('/api/v1/appointments') && response.request().method() === 'POST');
    await page.getByRole('button', { name: 'Book appointment', exact: true }).click();
    const booked = await response;
    expect(booked.status()).toBe(201);
    const receipt = await booked.json();
    await expect(page.getByRole('heading', { name: 'Appointment booked' })).toBeVisible();
    expect(receipt.audit_log.patient_id).toBe(session.patient.id);
    expect(receipt.audit_log.action_type).toBe('DEBIT');
    expect(Number(receipt.balance_before) - Number(receipt.balance_after)).toBeCloseTo(25, 2);
    await pause();
    await page.getByRole('link', { name: 'Audit trail', exact: true }).first().click();
    await expect(page.getByTestId('audit-patient')).toContainText(session.patient.name);
    await expect(page.getByText('Number of entries')).toBeVisible();
    await pause();
    await page.getByRole('button', { name: 'Choose demo actor' }).click();
    await page.getByLabel('Search permitted actors').fill(clinic.name);
    await page.getByRole('button', { name: `Clinic staff: ${clinic.name}`, exact: true }).click();
    await page.getByRole('link', { name: 'Browse', exact: true }).click();
    await page.getByRole('tab', { name: 'Appointments', exact: true }).click();
    await page.getByLabel('Search appointments by name or ID').fill(String(receipt.appointment.id));
    const visitRow = page.getByRole('row').filter({ has: page.getByText(String(receipt.appointment.id), { exact: true }) });
    await visitRow.getByRole('button', { name: `View details: ${session.patient.name}`, exact: true }).click();
    await page.getByRole('button', { name: 'Start consultation', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Discharge appointment', exact: true })).toBeVisible();
    await pause();
    await page.getByRole('button', { name: 'Discharge appointment', exact: true }).click();
    await expect(page.getByText('This visit is complete.')).toBeVisible();
    await pause();
    await page.getByRole('link', { name: 'Analytics', exact: true }).click();
    await expect(page.getByText('7-day moving average revenue', { exact: true })).toBeVisible();
    const refreshed = page.waitForResponse((response) => response.url().endsWith('/analytics/monthly/refresh'));
    await page.getByRole('button', { name: 'Refresh summary', exact: true }).click();
    expect((await refreshed).status()).toBe(200);
    await pause();
    await page.getByRole('link', { name: 'Map', exact: true }).click();
    await expect(page.getByRole('heading', { level: 1 })).toBeVisible();
    await expect(page.locator('.leaflet-container')).toBeVisible();
    await pause();
    await page.getByRole('link', { name: 'Reviews', exact: true }).click();
    await expect(page.getByTestId('reviews-screen')).toBeVisible();
    await expect(page.getByTestId('catalog-content')).toBeVisible();
    await pause();
    expect(errors).toEqual([]);
});
