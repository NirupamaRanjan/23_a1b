import psycopg2
import random
import os
from datetime import datetime, timedelta, timezone
from faker import Faker
try:
    from data_generation.india_geography import clinic_point
except ImportError:
    from india_geography import clinic_point



def connect():
    """Same PostgreSQL as the API: the root .env (DATABASE_URL or PG*), unless the older
    CARECONNECT_DB_* variables are set (bootstrap.py and earlier setups still pass those)."""
    if os.getenv("CARECONNECT_DB_NAME"):
        return psycopg2.connect(
            dbname=os.getenv("CARECONNECT_DB_NAME"),
            user=os.getenv("CARECONNECT_DB_USER", "postgres"),
            password=os.getenv("CARECONNECT_DB_PASSWORD"),
            host=os.getenv("CARECONNECT_DB_HOST", "localhost"),
            port=os.getenv("CARECONNECT_DB_PORT", "5432"))
    import sys
    from pathlib import Path
    sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "api"))
    from app.config import Settings   # loads the root .env
    return psycopg2.connect(Settings().database_url)

# Optional: set CARECONNECT_SEED (e.g. 2026) to get the same names/data on every run.
# Without it, every run generates new random data.
SEED = os.getenv("CARECONNECT_SEED")
fake = Faker("en_IN")

# Faker has no clinic-name provider, so only the kind of facility is listed here;
# the distinctive part of every clinic name is generated by Faker.
CLINIC_TYPES = ["Medical Center", "Family Clinic", "Health Center", "Urgent Care", "Community Clinic"]


def patient_names(count):
    """Unique realistic 'First Last' names (no titles such as Dr./MD)."""
    names = set()
    while len(names) < count:
        names.add(f"{fake.first_name()} {fake.last_name()}")
    names = sorted(names)
    random.shuffle(names)
    return names


def clinic_names(count):
    """Unique Faker-generated clinic names, e.g. 'Port Jessica Health Center' or 'Morgan Urgent Care'."""
    generators = [fake.city, fake.last_name, fake.street_name]
    names = set()
    while len(names) < count:
        names.add(f"{random.choice(generators)()} {random.choice(CLINIC_TYPES)}")
    names = sorted(names)
    random.shuffle(names)
    return names


def seed():
    if SEED:
        random.seed(int(SEED))
        Faker.seed(int(SEED))

    conn = connect()
    cur = conn.cursor()

    print("Clearing old data...")
    # wallet_audit_logs is append-only (see sql/03); switch its guard triggers off only for this reset.
    cur.execute("ALTER TABLE wallet_audit_logs DISABLE TRIGGER USER;")
    cur.execute("TRUNCATE TABLE appointments, wallet_audit_logs, patients, clinics RESTART IDENTITY CASCADE;")
    cur.execute("ALTER TABLE wallet_audit_logs ENABLE TRIGGER USER;")
    conn.commit()

    print("Seeding Patients...")
    patients_data = [(name, random.uniform(100.0, 5000.0)) for name in patient_names(1000)]
    cur.executemany("INSERT INTO patients (name, hsa_balance) VALUES (%s, %s)", patients_data)

    print("Seeding Clinics...")
    # Generate only in approved inland Indian service areas, centred around Hyderabad.
    # About 20% of clinics (10 of 50) are not accepting patients, so the Browse filter and the
    # "clinic not accepting" booking failure can be demonstrated. Clinic 1 (the default clinic in
    # a new session) always accepts.
    not_accepting = set(random.sample(range(2, 51), 10))
    clinics_data = [(name, *clinic_point(clinic_id - 1),
                     clinic_id not in not_accepting)
                    for clinic_id, name in enumerate(clinic_names(50), start=1)]
    cur.executemany("INSERT INTO clinics (name, latitude, longitude, is_accepting_patients) VALUES (%s, %s, %s, %s)", clinics_data)
    conn.commit()

    print("Seeding Appointments (50,000)...")
    start_date = datetime.now(timezone.utc) - timedelta(days=60)
    appointments = []
    for _ in range(50000):
        p_id = random.randint(1, 1000)
        c_id = random.randint(1, 50)
        copay = round(random.uniform(10.0, 150.0), 2)
        created_at = start_date + timedelta(minutes=random.randint(0, 86400))
        appointments.append((p_id, c_id, copay, 'DISCHARGED', created_at))

    cur.executemany("""
        INSERT INTO appointments (patient_id, clinic_id, copay_amount, status, created_at)
        VALUES (%s, %s, %s, %s, %s)
    """, appointments)

    print("Generating Ledger/Audit Logs (100,000 updates)...")
    # Patient ids are 1..1000 in insertion order (RESTART IDENTITY). Balances are tracked here so
    # debits never take an HSA below zero (the table has a non-negative CHECK constraint).
    balances = {i: round(balance, 2) for i, (_, balance) in enumerate(patients_data, start=1)}
    for _ in range(100000):
        p_id = random.randint(1, 1000)
        amt = round(random.uniform(5.0, 50.0), 2)
        # About a third of the entries are HSA spending (DEBIT); the rest are top-ups (CREDIT).
        if random.random() < 0.35 and balances[p_id] - amt >= 1:
            amt = -amt
        balances[p_id] = round(balances[p_id] + amt, 2)
        cur.execute("UPDATE patients SET hsa_balance = hsa_balance + %s WHERE id = %s", (amt, p_id))

    print("Spreading audit timestamps over the seeded 60 days...")
    # The audit trigger stamps each row with NOW(), which is the same instant for this whole
    # seeding transaction. Spread the rows over the seeded period in id order so the Audit
    # screen's date filter is meaningful; the (timestamp, id) order and every running balance
    # stay exactly the same. Guard triggers are switched off only for this one-time fix-up.
    cur.execute("ALTER TABLE wallet_audit_logs DISABLE TRIGGER USER;")
    cur.execute("""
        UPDATE wallet_audit_logs
        SET timestamp = %s + (id - 1) * (INTERVAL '60 days' / (SELECT MAX(id) FROM wallet_audit_logs))
    """, (start_date,))
    cur.execute("ALTER TABLE wallet_audit_logs ENABLE TRIGGER USER;")

    conn.commit()
    cur.close()
    conn.close()
    print("PostgreSQL Data Generation Complete!")


if __name__ == "__main__":
    seed()
