import random
import os
from datetime import datetime, timedelta, timezone
from faker import Faker
from pymongo import MongoClient

try:  # run as a script: python data_generation/mongo_seeder.py
    import nurse_telemetry as telemetry
except ImportError:  # imported by api/scripts/bootstrap.py
    from data_generation import nurse_telemetry as telemetry

# Optional: set CARECONNECT_SEED (e.g. 2026) to get the same names/data on every run.
# Without it, every run generates new random data.
SEED = os.getenv("CARECONNECT_SEED")
fake = Faker("en_US")

NURSE_COUNT = 500


def unique_person_names(count):
    """Unique realistic 'First Last' names generated by Faker (no titles such as Dr./MD)."""
    names = set()
    while len(names) < count:
        names.add(f"{fake.first_name()} {fake.last_name()}")
    names = sorted(names)
    random.shuffle(names)
    return names


def seed():
    if SEED:
        random.seed(int(SEED))
        Faker.seed(int(SEED))

    client = MongoClient(os.getenv("CARECONNECT_MONGO_URI", "mongodb://localhost:27017/"))
    db = client[os.getenv("CARECONNECT_MONGO_DB", "careconnect")]

    # Re-running the seeder replaces the data instead of appending to it.
    for name in ("Nurses", "NursePings", "PatientReviews", "MedicalCatalogs"):
        db[name].delete_many({})

    # 0. Nurse directory: a Faker name and a home point near one of the clinics for every nurse.
    #    Pings expire after 2 hours (TTL); the directory does not, so scripts/fresh_pings.py can
    #    keep generating telemetry for the same nurses later.
    print(f"Seeding Nurses ({NURSE_COUNT})...")
    clinics = telemetry.clinic_locations()
    homes = telemetry.nurse_homes(NURSE_COUNT, clinics)
    nurses = []
    for nurse_id, (name, (clinic_id, (home_lat, home_lng))) in enumerate(
            zip(unique_person_names(NURSE_COUNT), homes), start=1):
        nurses.append({"nurse_id": nurse_id, "name": name, "clinic_id": clinic_id,
                       "home": {"type": "Point", "coordinates": [home_lng, home_lat]}})
    db.Nurses.insert_many(nurses)
    db.Nurses.create_index("nurse_id", unique=True)
    print(f"  {NURSE_COUNT} nurses around {len(clinics) or 'the default'} clinic locations")

    # 1. Seed 500,000 Geospatial Telemetry Pings: 1,000 per nurse, one every 6 seconds over the
    #    last 100 minutes, each a small move from the previous one. The newest ping of each
    #    nurse is "now", so the seeded map stays populated for the full 2-hour TTL.
    pings_per_nurse = 500000 // NURSE_COUNT
    interval = timedelta(minutes=100) / pings_per_nurse
    now = datetime.now(timezone.utc)
    print("Seeding NursePings (500,000 pings)...")
    pings = []
    batch_size = 50000
    inserted = 0
    for nurse in nurses:
        home_lng, home_lat = nurse["home"]["coordinates"]
        lat, lng = telemetry.random_point_near(home_lat, home_lng, telemetry.HOME_RADIUS_M)
        active = random.random() < telemetry.ON_DUTY_SHARE
        for j in range(pings_per_nurse):
            lat, lng = telemetry.step(lat, lng, home_lat, home_lng)
            active = telemetry.next_duty(active, flip_rate=0.002)
            created_at = now - interval * (pings_per_nurse - 1 - j)
            pings.append(telemetry.ping(nurse["nurse_id"], nurse["name"], lat, lng, active, created_at))
            if len(pings) == batch_size:
                db.NursePings.insert_many(pings)
                inserted += len(pings)
                pings = []
                print(f"Inserted {inserted} pings...")
    if pings:
        db.NursePings.insert_many(pings)

    # 2. Seed Patient Reviews
    #    patient_id points to patients.id in PostgreSQL, where the patient names live.
    print("Seeding PatientReviews...")
    tags = ["Friendly", "Punctual", "Attentive", "Rushed", "Professional", "Empathetic"]
    reviews = []
    for _ in range(5000):
        reviews.append({
            "patient_id": random.randint(1, 1000),
            "rating": random.randint(1, 5),
            "bedside_manner_tags": random.sample(tags, k=random.randint(1, 3)),
            "created_at": datetime.now(timezone.utc)
        })
    db.PatientReviews.insert_many(reviews)

    # 3. Seed MedicalCatalogs (specialty, availability, medication details; see docs/mongo_schema_map.json)
    #    "physician" is an extra flexible field; the Reviews screen lists it under "Additional fields".
    print("Seeding MedicalCatalogs...")
    specialties = ["General Practice", "Cardiology", "Dermatology", "Pediatrics", "Orthopedics", "Neurology", "Psychiatry", "ENT"]
    days = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat"]
    medications = [("Paracetamol", "500 mg", "oral"), ("Amoxicillin", "250 mg", "oral"), ("Ibuprofen", "400 mg", "oral"),
                   ("Cetirizine", "10 mg", "oral"), ("Metformin", "500 mg", "oral"), ("Salbutamol", "100 mcg", "inhaled")]
    physicians = iter(unique_person_names(len(specialties) * 5))
    catalogs = []
    for specialty in specialties:
        for _ in range(5):
            med = random.choice(medications)
            catalogs.append({
                "specialty": specialty,
                "physician": f"Dr. {next(physicians)}",
                "availability_slots": [
                    {"day": d, "start": f"{random.choice([8, 9, 10])}:00", "end": f"{random.choice([14, 16, 18])}:00"}
                    for d in random.sample(days, k=random.randint(2, 4))
                ],
                "medication_details": {"name": med[0], "strength": med[1], "route": med[2]},
                "created_at": datetime.now(timezone.utc)
            })
    db.MedicalCatalogs.insert_many(catalogs)
    print("MongoDB Data Generation Complete!")


if __name__ == "__main__":
    seed()
